static uint32_t clamp_u32_i64(int64_t value, uint32_t maximum) {
    if (value <= 0) return 0u;
    if ((uint64_t)value >= maximum) return maximum;
    return (uint32_t)value;
}

static int32_t q16_mul_signed(int32_t a, int32_t b) {
    int64_t value = (int64_t)a * (int64_t)b;
    value += value >= 0 ? 32768 : -32768;
    value >>= 16;

    if (value > INT32_MAX) return INT32_MAX;
    if (value < INT32_MIN) return INT32_MIN;
    return (int32_t)value;
}

static uint32_t q16_mul_unsigned(uint32_t a, uint32_t b) {
    uint64_t value = (uint64_t)a * (uint64_t)b + 32768u;
    value >>= 16;
    return value > UINT32_MAX ? UINT32_MAX : (uint32_t)value;
}

static bool invert_matrix_q16(
    const int32_t in[9],
    int32_t out[9]
) {
    int64_t a = in[0], b = in[1], c = in[2];
    int64_t d = in[3], e = in[4], f = in[5];
    int64_t g = in[6], h = in[7], i = in[8];

    /*
     * Cofactors are Q32; determinant after multiplying by one Q16 matrix term
     * is Q48. With normalized ICC XYZ matrices this remains safely in int64.
     */
    int64_t A = e * i - f * h;
    int64_t B = c * h - b * i;
    int64_t C = b * f - c * e;
    int64_t D = f * g - d * i;
    int64_t E = a * i - c * g;
    int64_t F = c * d - a * f;
    int64_t G = d * h - e * g;
    int64_t H = b * g - a * h;
    int64_t I = a * e - b * d;

    int64_t determinant = a * A + b * D + c * G;

    if (determinant > -(INT64_C(1) << 28) &&
        determinant < (INT64_C(1) << 28)) {
        return false;
    }

    const int64_t cofactors[9] = {
        A, B, C,
        D, E, F,
        G, H, I
    };

    for (uint32_t n = 0u; n < 9u; ++n) {
        /*
         * inverse(Q16) = cofactor(Q32) * 2^32 / determinant(Q48)
         * represented as Q16 => multiply cofactor by 2^32.
         * Cofactors for color matrices are bounded well below 2^31, making
         * this 64-bit operation safe after a normalization step.
         */
        int64_t co = cofactors[n];
        int64_t numerator;

        if (co > (INT64_MAX >> 16) ||
            co < (INT64_MIN >> 16)) {
            return false;
        }

        numerator = co << 16;
        int64_t determinant_scaled = determinant >> 16;

        if (determinant_scaled == 0) {
            return false;
        }

        int64_t value =
            numerator / determinant_scaled;

        if (value > INT32_MAX || value < INT32_MIN) {
            return false;
        }

        out[n] = (int32_t)value;
    }

    return true;
}

static void identity_curve(uint16_t *curve, uint32_t samples) {
    for (uint32_t i = 0u; i < samples; ++i) {
        curve[i] = (uint16_t)(
            ((uint64_t)i * 65535u + (samples - 1u) / 2u) /
            (samples - 1u)
        );
    }
}

static void profile_identity(
    struct aurora_color_output_profile *profile
) {
    *profile = (struct aurora_color_output_profile){0};

    profile->valid = true;
    profile->has_icc_matrix = true;
    profile->has_icc_trc = false;
    profile->has_calibration_1d = true;

    /* D50 PCS XYZ -> linear sRGB, Bradford-adapted approximation. */
    const int32_t matrix[9] = {
         205413, -105980,  -32158,
         -64143,  125573,    2192,
           4714,  -15004,   92072
    };

    for (uint32_t i = 0u; i < 9u; ++i) {
        profile->pcs_to_device_q16[i] = matrix[i];
    }

    for (uint32_t c = 0u; c < 3u; ++c) {
        identity_curve(
            profile->encode_trc[c],
            AURORA_COLOR_PROFILE_CURVE_SAMPLES
        );
        identity_curve(
            profile->calibration_1d[c],
            AURORA_COLOR_CALIBRATION_SAMPLES
        );
    }

    profile->target_peak_nits_q16 =
        COLOR_SDR_REFERENCE_WHITE_NITS * 65536u;
    profile->target_black_nits_q16 = 0u;
}

