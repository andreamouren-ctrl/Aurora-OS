static uint16_t read_be16(const uint8_t *p) {
    return (uint16_t)(((uint16_t)p[0] << 8) | p[1]);
}

static uint32_t read_be32(const uint8_t *p) {
    return ((uint32_t)p[0] << 24) |
        ((uint32_t)p[1] << 16) |
        ((uint32_t)p[2] << 8) |
        (uint32_t)p[3];
}

static int32_t read_s15fixed16(const uint8_t *p) {
    return (int32_t)read_be32(p);
}

static uint32_t lut_interp_u16(
    const uint16_t *table,
    uint16_t input
) {
    uint64_t position =
        ((uint64_t)input * COLOR_LUT_INTERVALS * 65536u) /
        65535u;
    uint32_t index = (uint32_t)(position >> 16);
    uint32_t fraction = (uint32_t)(position & 0xFFFFu);

    if (index >= COLOR_LUT_INTERVALS) {
        return table[COLOR_LUT_INTERVALS];
    }

    uint32_t a = table[index];
    uint32_t b = table[index + 1u];
    int32_t delta = (int32_t)b - (int32_t)a;

    int64_t value =
        (int64_t)a +
        (((int64_t)delta * fraction + 32768) >> 16);

    if (value < 0) return 0u;
    if (value > 65535) return 65535u;
    return (uint32_t)value;
}

