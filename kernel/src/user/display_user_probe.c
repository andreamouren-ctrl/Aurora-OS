#include <stddef.h>
#include <stdint.h>

#include <aurora/display_user_probe.h>

/*
 * x86-64 Ring 3 G1 display probe.
 *
 * Kernel preload:
 *   [RSP-8]  display capability
 *   [RSP-16] private user frame address
 *   [RSP-24] frame byte length
 *
 * The probe invokes AURORA_SYS_DISPLAY_PRESENT twice and stores the returned
 * presentation serials at [RSP-32] and [RSP-40]. It has no framebuffer mapping
 * or device-I/O capability.
 */
static const uint8_t probe_image[] = {
    0x4c,0x8b,0x64,0x24,0xf8,0x4c,0x8b,0x6c,0x24,0xf0,0x4c,0x8b,0x74,0x24,0xe8,
    0x48,0xc7,0xc0,0x14,0x00,0x00,0x00,0x4c,0x89,0xe7,0x4c,0x89,0xee,0x4c,0x89,
    0xf2,0x0f,0x05,0x48,0x83,0xf8,0xff,0x74,0x3c,0x48,0x85,0xc0,0x74,0x37,0x48,
    0x89,0x44,0x24,0xe0,0x49,0x89,0xc7,0x48,0xc7,0xc0,0x14,0x00,0x00,0x00,0x4c,
    0x89,0xe7,0x4c,0x89,0xee,0x4c,0x89,0xf2,0x0f,0x05,0x48,0x83,0xf8,0xff,0x74,
    0x17,0x4c,0x39,0xf8,0x76,0x12,0x48,0x89,0x44,0x24,0xd8,0x48,0xc7,0xc0,0x03,
    0x00,0x00,0x00,0x31,0xff,0x0f,0x05,0x0f,0x0b,0x48,0xc7,0xc0,0x03,0x00,0x00,
    0x00,0xbf,0x01,0x00,0x00,0x00,0x0f,0x05,0x0f,0x0b
};

const uint8_t *display_user_probe_image(void) {
    return probe_image;
}

size_t display_user_probe_image_size(void) {
    return sizeof(probe_image);
}
