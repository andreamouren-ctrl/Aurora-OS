#include <stddef.h>
#include <stdint.h>

#include <aurora/entropy_user_probe.h>

/*
 * x86-64 Ring 3 entropy probe.
 *
 * The kernel writes one AURORA_CAP_ENTROPY handle at [RSP-8]. The probe asks
 * AURORA_SYS_ENTROPY_SEED for 32 bytes into its user stack, rejects an all-zero
 * result, then exits 0. Any syscall/capability/seed failure exits 1.
 */
static const uint8_t probe_image[] = {
    0x4c, 0x8b, 0x64, 0x24, 0xf8, 0x4c, 0x89, 0xe7,
    0x48, 0x8d, 0x74, 0x24, 0xc0, 0xba, 0x20, 0x00,
    0x00, 0x00, 0xb8, 0x09, 0x00, 0x00, 0x00, 0x0f,
    0x05, 0x48, 0x85, 0xc0, 0x75, 0x21, 0x48, 0x8b,
    0x44, 0x24, 0xc0, 0x48, 0x0b, 0x44, 0x24, 0xc8,
    0x48, 0x0b, 0x44, 0x24, 0xd0, 0x48, 0x0b, 0x44,
    0x24, 0xd8, 0x74, 0x0b, 0xb8, 0x03, 0x00, 0x00,
    0x00, 0x31, 0xff, 0x0f, 0x05, 0x0f, 0x0b, 0xb8,
    0x03, 0x00, 0x00, 0x00, 0xbf, 0x01, 0x00, 0x00,
    0x00, 0x0f, 0x05, 0x0f, 0x0b
};

const uint8_t *entropy_user_probe_image(void) {
    return probe_image;
}

size_t entropy_user_probe_image_size(void) {
    return sizeof(probe_image);
}
