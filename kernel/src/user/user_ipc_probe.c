#include <stddef.h>
#include <stdint.h>

#include <aurora/user_ipc_probe.h>

/*
 * x86-64 Ring 3 IPC probe.
 *
 * The kernel writes the process-local IPC endpoint handle at [RSP-8] and
 * pre-queues one payload for that endpoint. The probe receives the message
 * into [RSP-512], echoes the received payload back through the same endpoint,
 * publishes AURORA_USER_IPC_PROBE_MAGIC, then exits.
 *
 * Syscall ABI:
 *   receive: rax=5, rdi=endpoint, rsi=struct aurora_sys_ipc_received *
 *   send:    rax=4, rdi=endpoint, rsi=data, rdx=len, r10=transfers, r8=count
 */
static const uint8_t probe_image[] = {
    0x48, 0x8B, 0x7C, 0x24, 0xF8,
    0x48, 0x8D, 0xB4, 0x24, 0x00, 0xFE, 0xFF, 0xFF,
    0xB8, 0x05, 0x00, 0x00, 0x00,
    0x0F, 0x05,
    0x48, 0x85, 0xC0,
    0x75, 0x3F,
    0x8B, 0x94, 0x24, 0x00, 0xFE, 0xFF, 0xFF,
    0x48, 0x8D, 0xB4, 0x24, 0x08, 0xFE, 0xFF, 0xFF,
    0x48, 0x8B, 0x7C, 0x24, 0xF8,
    0x45, 0x31, 0xD2,
    0x45, 0x31, 0xC0,
    0xB8, 0x04, 0x00, 0x00, 0x00,
    0x0F, 0x05,
    0x48, 0x85, 0xC0,
    0x75, 0x19,
    0x31, 0xC0,
    0x48, 0xBF,
    0x50, 0x49, 0x41, 0x52, 0x4F, 0x52, 0x55, 0x41,
    0x0F, 0x05,
    0xB8, 0x03, 0x00, 0x00, 0x00,
    0x31, 0xFF,
    0x0F, 0x05,
    0x0F, 0x0B,
    0xB8, 0x03, 0x00, 0x00, 0x00,
    0xBF, 0x01, 0x00, 0x00, 0x00,
    0x0F, 0x05,
    0x0F, 0x0B
};

const uint8_t *user_ipc_probe_image(void) {
    return probe_image;
}

size_t user_ipc_probe_image_size(void) {
    return sizeof(probe_image);
}
